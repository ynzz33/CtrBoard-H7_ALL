function result=run_mpc10()
%RUN_MPC10 大机原十态模型/Q/R，2ms、20输入区间（40ms）；只生成候选，不覆盖原LQR表。
here=fileparts(mfilename('fullpath'));parent=fileparts(here);root=fileparts(fileparts(parent));
saved=path;cleanup=onCleanup(@()path(saved));
addpath(parent,fullfile(parent,'lqr10'),fullfile(parent,'mpc_common'));
m=machine_table('big_wheelleg');
source=fileread(fullfile(root,'imcalib','Algorithm','lqr','lqr_gain_big.c'));
q=regexp(source,'\*\s*Q\s*:\s*diag\(\[([^\]]+)\]\)','tokens','once');
r=regexp(source,'\*\s*R\s*:\s*diag\(\[([^\]]+)\]\)','tokens','once');
assert(~isempty(q)&&~isempty(r),'mpc10:weights');q=sscanf(q{1},'%f');r=sscanf(r{1},'%f');
assert(numel(q)==10&&numel(r)==4&&all(q>0)&&all(r>0));
% 作者要求：全部输入权重R×5，验证MPC是否因输入代价过轻而偏向轮。
r=r*5;
Q=diag(q);R=diag(r);input_scale=1./sqrt(r);grid=m.ctrl.grid;n=numel(grid);
Ts=.002;N=20;rho=4;terminal_scale=1.01;
data=zeros(240,n,n);
for i=1:n
    for j=1:n
        [A,B]=model_AB('sjtu5',m,grid(i),grid(j));[A,B]=c2d(A,B,Ts);
        [~,P]=dlqr(A,B,Q,R);P=terminal_scale*(P+P')/2;
        B=B*diag(input_scale);
        data(:,i,j)=[reshape(A',[],1);reshape(B',[],1);reshape(P',[],1)];
    end
end
data=double(single(data)); % 按实际导出精度验证，不只验证双精度源。
% 网格及每个单元中心；只验插值定义的问题，不把P称为该模型精确DARE。
worst_residual=-inf;worst_pole=0;count=0;max_model_error=0;
points=sort([grid,(grid(1:end-1)+grid(2:end))/2]);
for i=1:numel(points)
    for j=1:numel(points)
        % 289格点和256中心，共545点；不做无必要的全交叉细网格。
        if mod(i,2)~=mod(j,2),continue;end
        l=points(i);rr=points(j);v=pick(data,grid,l,rr);
        A=reshape(v(1:100),10,10)';B=reshape(v(101:140),4,10)';P=reshape(v(141:240),10,10)';
        K=(eye(4)+B'*P*B)\(B'*P*A);
        residual=Q+A'*P*A-A'*P*B*K-P;
        normalized=diag(1./sqrt(q))*residual*diag(1./sqrt(q));
        worst_residual=max(worst_residual,max(eig((normalized+normalized')/2)));
        worst_pole=max(worst_pole,max(abs(eig(A-B*K))));
        [Ae,Be]=model_AB('sjtu5',m,l,rr);[Ae,Be]=c2d(Ae,Be,Ts);
        max_model_error=max(max_model_error,max(abs([A-Ae,B-Be*diag(input_scale)]),[],'all'));
        count=count+1;
    end
end
assert(worst_residual<0 && worst_pole<1,'mpc10 terminalInterpolation');
worst_hold_pole=0;hold_checks=0;
for i=1:4:n,for j=1:4:n
 v=data(:,i,j);A=reshape(v(1:100),10,10)';B=reshape(v(101:140),4,10)';P=reshape(v(141:240),10,10)';
 free=mpc_build(A,B,Q,eye(4),P,N,0);K=free.K(:,:,1);
 for dl=[-.005 .005],for dr=[-.005 .005]
  ll=grid(i)+dl;lr=grid(j)+dr;if ll<grid(1)||lr<grid(1)||ll>grid(end)||lr>grid(end),continue;end
  [At,Bt]=model_AB('sjtu5',m,ll,lr);[At,Bt]=c2d(At,Bt,Ts);
  worst_hold_pole=max(worst_hold_pole,max(abs(eig(At-Bt*diag(input_scale)*K))));hold_checks=hold_checks+1;
 end;end
end;end
assert(worst_hold_pole<1,'mpc10 held-model pole');

out=fullfile(here,'output');if ~isfolder(out),mkdir(out);end
h=fopen(fullfile(out,'balance_mpc_data.h'),'w');assert(h>=0);
fprintf(h,['/* Generated by run_mpc10: normalized input, physical state/Q, frozen-leg LPV. */\n' ...
'#ifndef BALANCE_MPC_DATA_H\n#define BALANCE_MPC_DATA_H\n#include "mpc_solver.h"\n' ...
'#define BALANCE_MPC_N %du\n#define BALANCE_MPC_GRID_N %du\n#define BALANCE_MPC_TS %.9ef\n' ...
'#define BALANCE_MPC_WORK_SIZE MPC_WORKSPACE_FLOATS(10u,4u,BALANCE_MPC_N)\n' ...
'extern const float balance_mpc_grid[BALANCE_MPC_GRID_N];\n' ...
'extern const float balance_mpc_grid_data[BALANCE_MPC_GRID_N*BALANCE_MPC_GRID_N*240u];\n' ...
'extern const float balance_mpc_Q[100],balance_mpc_R[16],balance_mpc_input_scale[4];\n' ...
'#endif\n'],N,n,Ts);fclose(h);
f=fopen(fullfile(out,'balance_mpc_data.c'),'w');assert(f>=0);closer=onCleanup(@()fclose(f));
fprintf(f,'/* Generated 17x17 original-model grid; terminal=1.01*physical DARE, input scale=1/sqrt(R). */\n#include "balance_mpc_data.h"\n');
emit(f,'balance_mpc_grid',grid);emit(f,'balance_mpc_Q',reshape(Q',[],1));emit(f,'balance_mpc_R',reshape(eye(4),[],1));emit(f,'balance_mpc_input_scale',input_scale);
% 左下标优先：C index=(il*n+ir)*240。
ordered=permute(data,[1 3 2]);emit(f,'balance_mpc_grid_data',ordered(:));
result=struct('Ts',Ts,'N',N,'rho',rho,'Q',Q,'R',R,'grid',grid,'data',data, ...
    'input_scale',input_scale,'terminal_scale',terminal_scale,'validation_points',count, ...
    'worst_hold_pole',worst_hold_pole,'hold_checks',hold_checks,'worst_terminal_residual',worst_residual,'worst_pole',worst_pole,'max_model_error',max_model_error);
save(fullfile(out,'result_latest.mat'),'result');
fprintf('mpc10 grid=%dx%d, validation=%d, residual %.9g, pole %.9g, max Ad/Bhat error %.9g\n',n,n,count,worst_residual,worst_pole,max_model_error);
end
function v=pick(data,grid,l,r)
n=numel(grid);i=min(n-1,max(1,find(grid<=l,1,'last')));j=min(n-1,max(1,find(grid<=r,1,'last')));
x=(l-grid(i))/(grid(i+1)-grid(i));y=(r-grid(j))/(grid(j+1)-grid(j));
v=(1-x)*(1-y)*data(:,i,j)+x*(1-y)*data(:,i+1,j)+(1-x)*y*data(:,i,j+1)+x*y*data(:,i+1,j+1);
end
function emit(f,name,values)
fprintf(f,'const float %s[%d]={\n',name,numel(values));
for i=1:numel(values),fprintf(f,'%.9ef,',single(values(i)));if mod(i,8)==0,fprintf(f,'\n');end;end
fprintf(f,'\n};\n');
end
